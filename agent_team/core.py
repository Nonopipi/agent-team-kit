"""Strict configuration rendering and conservative file updates. AGPL-3.0."""

import datetime
import hashlib
import json
import os
import re
import tempfile
import tomllib
from pathlib import Path


MAX_SOURCE_BYTES = 1024 * 1024
MANIFEST = '.agent-team-generated.json'
NAME = re.compile(r'[a-z][a-z0-9_-]{0,63}\Z')
MANAGED_AGENT = re.compile(r'\.(?:codex/agents/[a-z][a-z0-9_-]{0,63}\.toml|claude/agents/[a-z][a-z0-9_-]{0,63}\.md)\Z')


def _fields(value, expected, label):
    if not isinstance(value, dict):
        raise ValueError(f'{label} must be a table')
    unknown, missing = set(value) - expected, expected - set(value)
    if unknown or missing:
        raise ValueError(f'{label}: unknown fields {sorted(unknown)}; missing fields {sorted(missing)}')


def _text(value, label, limit):
    if not isinstance(value, str) or not value.strip() or len(value) > limit:
        raise ValueError(f'{label} must be non-empty text of at most {limit} characters')
    if any((ord(c) < 32 and c not in '\n\r\t') or ord(c) == 127 for c in value):
        raise ValueError(f'{label} contains an unsupported control character')


def validate(spec):
    _fields(spec, {'schema_version', 'modified_date', 'codex', 'agents'}, 'spec')
    if type(spec['schema_version']) is not int or spec['schema_version'] != 1:
        raise ValueError('schema_version must be integer 1')
    date = spec['modified_date']
    if not isinstance(date, str) or not re.fullmatch(r'\d{4}-\d{2}-\d{2}', date):
        raise ValueError('modified_date must be an ISO date: YYYY-MM-DD')
    try:
        datetime.date.fromisoformat(date)
    except ValueError as exc:
        raise ValueError('modified_date is not a valid calendar date') from exc
    settings = spec['codex']
    _fields(settings, {'enabled', 'max_concurrent_threads_per_session'}, 'codex')
    if type(settings['enabled']) is not bool:
        raise ValueError('codex.enabled must be a boolean')
    count = settings['max_concurrent_threads_per_session']
    if type(count) is not int or not 1 <= count <= 64:
        raise ValueError('codex.max_concurrent_threads_per_session must be an integer from 1 to 64')
    agents = spec['agents']
    if not isinstance(agents, list) or not 1 <= len(agents) <= 64:
        raise ValueError('agents must contain between 1 and 64 definitions')
    names, claude_names = set(), set()
    for index, agent in enumerate(agents):
        label = f'agents[{index}]'
        _fields(agent, {'name', 'description', 'instructions'}, label)
        name = agent['name']
        if not isinstance(name, str) or not NAME.fullmatch(name):
            raise ValueError(f'{label}.name must start with a lowercase letter and use only lowercase letters, digits, underscores or hyphens (max 64)')
        claude = name.replace('_', '-')
        if name in names or claude in claude_names:
            raise ValueError(f'duplicate agent name or Claude-name collision: {name}')
        names.add(name)
        claude_names.add(claude)
        _text(agent['description'], f'{label}.description', 2048)
        _text(agent['instructions'], f'{label}.instructions', 65536)
    return spec


def load_spec(path):
    path = Path(path)
    if path.stat().st_size > MAX_SOURCE_BYTES:
        raise ValueError('source exceeds the 1 MiB size limit')
    data = path.read_bytes()
    if len(data) > MAX_SOURCE_BYTES:
        raise ValueError('source exceeds the 1 MiB size limit')
    return validate(tomllib.loads(data.decode('utf-8')))


def _quoted(text):
    return json.dumps(text, ensure_ascii=False)


def _multiline(text):
    escaped = ''.join('\n' if c == '\n' else _quoted(c)[1:-1] for c in text)
    return '"""\n' + escaped + '"""'


def render(spec):
    validate(spec)
    date = spec['modified_date']
    notice = f'Adapted from Aidan-M-Dev/claude-code-agents; AGPL-3.0. Modified {date}.'
    banner = '# Generated by agent-team-kit from team.toml. Do not edit directly.\n# ' + notice + '\n'
    settings = spec['codex']
    files = {'.codex/config.toml': banner + '\n[agents]\n'
             + f'enabled = {str(settings["enabled"]).lower()}\n'
             + f'max_concurrent_threads_per_session = {settings["max_concurrent_threads_per_session"]}\n'}
    mapping = []
    for agent in sorted(spec['agents'], key=lambda a: a['name']):
        name, description, instructions = (agent[k] for k in ('name', 'description', 'instructions'))
        claude_name = name.replace('_', '-')
        files[f'.codex/agents/{name}.toml'] = (banner + f'\nname = {_quoted(name)}\n'
            + f'description = {_quoted(description)}\n'
            + f'developer_instructions = {_multiline(instructions)}\n')
        files[f'.claude/agents/{claude_name}.md'] = ('---\n'
            + f'name: {_quoted(claude_name)}\ndescription: {_quoted(description)}\n---\n\n'
            + f'<!-- Generated by agent-team-kit. {notice} -->\n\n' + instructions)
        mapping.append(f'| `{name}` | `{claude_name}` |')
    files['CLAUDE.md'] = ('<!-- Generated by agent-team-kit. ' + notice + ' -->\n'
        + '# Claude Code project instructions\n\n@AGENTS.md\n\n'
        + 'Use the shared project rules in AGENTS.md. The main conversation is the\n'
        + 'coordinator and implementer; use the risk-based workflow in Part B.\n'
        + 'Delegate only when justified. Specialists follow Part A and their own instructions.\n'
        + 'References to Codex role files mean the corresponding Claude Code role\n'
        + 'below. Keep the shared prompt text unchanged and use these names when\n'
        + 'delegating in Claude Code. Run one specialist at a time.\n\n'
        + '| Shared role / Codex name | Claude Code name |\n| --- | --- |\n'
        + '\n'.join(mapping) + '\n\n'
        + 'No model or permission override is generated. Each client applies its\n'
        + 'defaults and parent-session settings. Read-only instructions do not\n'
        + 'create a separate permission boundary.\n')
    for path, text in files.items():
        if path.endswith('.toml'):
            tomllib.loads(text)
    return files


def _digest(data):
    return hashlib.sha256(data).hexdigest()


def _managed(path):
    return path in {'CLAUDE.md', '.codex/config.toml'} or bool(MANAGED_AGENT.fullmatch(path))


def _root(output):
    path = Path(output).expanduser().absolute()
    if path.is_symlink() or (path.exists() and not path.is_dir()):
        raise ValueError('output must be a directory, not a file or symlink')
    return path.resolve()


def _safe_path(root, relative):
    path = root
    for component in Path(relative).parts:
        if component in {'..', '.'} or Path(relative).is_absolute():
            raise ValueError(f'unsafe output path: {relative}')
        path /= component
        if path.is_symlink():
            raise ValueError(f'refusing symlink in output path: {relative}')
        if path != root / relative and path.exists() and not path.is_dir():
            raise ValueError(f'output parent is not a directory: {relative}')
    if path.exists() and not path.is_file():
        raise ValueError(f'output target is not a regular file: {relative}')
    return path


def _read_manifest(root):
    path = _safe_path(root, MANIFEST)
    if not path.exists():
        return None
    if path.stat().st_size > MAX_SOURCE_BYTES:
        raise ValueError('generated-file manifest exceeds the size limit')
    data = json.loads(path.read_text(encoding='utf-8'))
    _fields(data, {'schema_version', 'files'}, 'generated-file manifest')
    if type(data['schema_version']) is not int or data['schema_version'] != 1 or not isinstance(data['files'], dict):
        raise ValueError('invalid generated-file manifest')
    for relative, digest in data['files'].items():
        if not _managed(relative) or not isinstance(digest, str) or not re.fullmatch(r'[0-9a-f]{64}', digest):
            raise ValueError('unsafe path or digest in generated-file manifest')
        _safe_path(root, relative)
    return data['files']


def _expected(files):
    if not isinstance(files, dict) or not files:
        raise ValueError('no generated files')
    for relative, text in files.items():
        if not _managed(relative) or not isinstance(text, str):
            raise ValueError('unsafe generated-file plan')
    return {path: _digest(text.encode('utf-8')) for path, text in sorted(files.items())}


def _atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix='.agent-team-', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(text)
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def generate(output, files):
    root = _root(output)
    expected = _expected(files)
    owned = _read_manifest(root) or {}
    rules = _safe_path(root, 'AGENTS.md')
    for relative in owned.keys() - expected.keys():
        if _safe_path(root, relative).exists():
            raise ValueError(f'removed role still has a managed file: {relative}; review and remove it explicitly, or use a new output directory')
    for relative in files:
        path = _safe_path(root, relative)
        if path.exists():
            actual = _digest(path.read_bytes())
            if actual != expected[relative] and actual != owned.get(relative):
                raise ValueError(f'refusing to overwrite changed or unmanaged file: {relative}')
    starter = Path(__file__).parent / 'templates/AGENTS.md'
    starter_text = starter.read_text(encoding='utf-8') if not rules.exists() else None
    # Check every conflict before creating directories or changing files.
    root.mkdir(parents=True, exist_ok=True)
    for relative, text in sorted(files.items()):
        path = _safe_path(root, relative)
        if not path.exists() or path.read_bytes() != text.encode('utf-8'):
            _atomic_write(path, text)
    if starter_text is not None:
        _atomic_write(_safe_path(root, 'AGENTS.md'), starter_text)
    manifest = json.dumps({'schema_version': 1, 'files': expected}, indent=2, sort_keys=True) + '\n'
    path = _safe_path(root, MANIFEST)
    if not path.exists() or path.read_text(encoding='utf-8') != manifest:
        _atomic_write(path, manifest)
    return len(files)


def check(output, files):
    root = _root(output)
    expected = _expected(files)
    owned = _read_manifest(root)
    issues = []
    for relative, digest in expected.items():
        path = _safe_path(root, relative)
        if not path.exists():
            issues.append(f'missing: {relative}')
        elif _digest(path.read_bytes()) != digest:
            issues.append(f'drift: {relative}')
    if owned != expected:
        issues.append('generated-file manifest is missing or differs from the source')
    if not _safe_path(root, 'AGENTS.md').exists():
        issues.append('missing shared project guidance: AGENTS.md')
    return issues
